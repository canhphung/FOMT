def extract_records(base):
    result = []
    for at, slots, expected in SPECS:
        slots = tuple(int(slot, 16) for slot in slots)
        raw = bytes.fromhex(expected)
        if cstring(base, at, at + len(raw) + 1) != raw or any(u32(base, slot) != ROM_BASE + at for slot in slots):
            raise FormatError('native shop/item literal mismatch: ' + hex(at))
        group = 'shop' if at < 0x110000 else 'item_window'
        result.append(make_record(f'ui.items.{at:06x}', raw, at, 'native_' + group,
            {'kind': 'pointer', 'pointer_offsets': list(slots),
             'reference': 'shop_text.SPECS; docs/ITEM_LOCALIZATION.md; verified native literal callers'}, 28))
    return result
